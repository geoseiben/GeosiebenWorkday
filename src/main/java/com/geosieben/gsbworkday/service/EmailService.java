    private int parseYearOrCurrent(String year) {
        if (year == null || year.isBlank()) {
            return LocalDate.now().getYear();
        }
        try {
            return Integer.parseInt(year.trim());
        } catch (NumberFormatException ex) {
            return LocalDate.now().getYear();
        }
    }

    private String escapeHtml(String value) {
        if (value == null) {
            return "";
        }
        return value
                .replace("&", "&amp;")
                .replace("<", "&lt;")
                .replace(">", "&gt;")
                .replace("\"", "&quot;")
                .replace("'", "&#39;");
    }
